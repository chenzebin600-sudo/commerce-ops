import { DATABASE_DIALECTS } from "./database-provider.mjs";

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export const DATABASE_VALUE_TYPES = Object.freeze({
  BOOLEAN: "boolean",
  INTEGER: "integer",
  BIGINT: "bigint",
  JSON: "json",
  TIMESTAMP: "timestamp",
  UUID: "uuid",
  TEXT: "text",
});

export const DATABASE_SCHEMA_COMPATIBILITY = Object.freeze({
  boolean: Object.freeze({ sqlite: "INTEGER (0/1)", postgresql: "boolean" }),
  json: Object.freeze({ sqlite: "TEXT (JSON)", postgresql: "jsonb" }),
  timestamp: Object.freeze({ sqlite: "TEXT (ISO-8601 UTC)", postgresql: "timestamptz" }),
  uuid: Object.freeze({ sqlite: "TEXT", postgresql: "uuid" }),
  identity: Object.freeze({ sqlite: "INTEGER PRIMARY KEY AUTOINCREMENT", postgresql: "GENERATED BY DEFAULT AS IDENTITY" }),
  indexes: Object.freeze({ sqlite: "CREATE INDEX / partial index", postgresql: "CREATE INDEX / partial index" }),
  foreignKeys: Object.freeze({ sqlite: "PRAGMA foreign_keys=ON", postgresql: "always enforced" }),
});

function normalizeTimestamp(value) {
  const date = value instanceof Date ? value : new Date(String(value));
  if (Number.isNaN(date.getTime())) throw new TypeError("Database timestamp is invalid");
  return date.toISOString();
}

function normalizeBoolean(value) {
  if (value === true || value === 1 || value === "1") return true;
  if (value === false || value === 0 || value === "0") return false;
  throw new TypeError("Database boolean is invalid");
}

function normalizeJson(value) {
  if (typeof value === "string") return JSON.parse(value);
  if (value !== null && typeof value === "object") return value;
  throw new TypeError("Database JSON value is invalid");
}

export function normalizeDatabaseValue(value, type) {
  if (value === null || value === undefined) return null;
  switch (type) {
    case DATABASE_VALUE_TYPES.BOOLEAN: return normalizeBoolean(value);
    case DATABASE_VALUE_TYPES.INTEGER: {
      const number = Number(value);
      if (!Number.isSafeInteger(number)) throw new TypeError("Database integer is invalid");
      return number;
    }
    case DATABASE_VALUE_TYPES.BIGINT: {
      const normalized = typeof value === "bigint" ? value.toString() : String(value);
      if (!/^-?\d+$/.test(normalized)) throw new TypeError("Database bigint is invalid");
      return normalized;
    }
    case DATABASE_VALUE_TYPES.JSON: return normalizeJson(value);
    case DATABASE_VALUE_TYPES.TIMESTAMP: return normalizeTimestamp(value);
    case DATABASE_VALUE_TYPES.UUID: {
      const normalized = String(value).toLowerCase();
      if (!UUID_PATTERN.test(normalized)) throw new TypeError("Database UUID is invalid");
      return normalized;
    }
    case DATABASE_VALUE_TYPES.TEXT: return String(value);
    default: throw new TypeError(`Unsupported database value type: ${type}`);
  }
}

export function encodeDatabaseValue(value, type, dialect) {
  if (value === null || value === undefined) return null;
  if (!Object.values(DATABASE_DIALECTS).includes(dialect)) throw new TypeError("Database dialect is invalid");
  const normalized = normalizeDatabaseValue(value, type);
  if (type === DATABASE_VALUE_TYPES.BOOLEAN && dialect === DATABASE_DIALECTS.SQLITE) return normalized ? 1 : 0;
  if (type === DATABASE_VALUE_TYPES.JSON && dialect === DATABASE_DIALECTS.SQLITE) return JSON.stringify(normalized);
  return normalized;
}
